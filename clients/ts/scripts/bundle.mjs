// bundle joins dist/*.js into one ES module, dist/loam.mjs, for callers that
// vendor a file rather than install a package (a plain .mjs service in a node
// image, with no package.json and no npm install). The modules are
// ours and few, so this is a concatenation in import order, not a bundler: it
// drops the relative imports, keeps the node: ones, and exports exactly what
// dist/index.js exports. It then imports the result to check that it loads
// and exports the same names.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const relImport = /^(?:import|export)[^;]*?from\s+"\.\/([^"]+)";\n/gm;
const nodeImport = /^import[^;]*?from\s+"node:[^"]+";\n/gm;

const files = readdirSync(dist).filter((f) => f.endsWith(".js"));
const src = Object.fromEntries(files.map((f) => [f, readFileSync(join(dist, f), "utf8")]));

// Order the modules so that each comes after everything it imports.
const order = [];
const state = {};
function visit(f) {
  if (state[f] === "done") return;
  if (state[f] === "visiting") throw new Error(`bundle: an import cycle through ${f}`);
  state[f] = "visiting";
  for (const m of src[f].matchAll(relImport)) visit(m[1]);
  state[f] = "done";
  order.push(f);
}
visit("index.js");

const imports = new Set();
const bodies = [];
for (const f of order) {
  if (f === "index.js") continue;
  let s = src[f];
  for (const m of s.matchAll(nodeImport)) imports.add(m[0].trim());
  s = s
    .replace(relImport, "")
    .replace(nodeImport, "")
    .replace(/^export \{\};\n/gm, "")
    .replace(/^export (?=(?:async |abstract )?(?:function|class|const|let|var)\b)/gm, "");
  if (/^export /m.test(s)) throw new Error(`bundle: ${f} has an export this script doesn't know how to inline`);
  bodies.push(`// ${f.replace(/\.js$/, ".ts")}\n${s.trim()}\n`);
}

const names = Object.keys(await import(pathToFileURL(join(dist, "index.js")).href)).sort();
const out = [
  `// @arugula-salad/loam ${pkg.version}: one-file build of clients/ts in github.com/arugula-salad/loam.`,
  `// Generated by scripts/bundle.mjs; don't edit. Node 20 or later, no dependencies.`,
  ...[...imports].sort(),
  "",
  ...bodies,
  `export { ${names.join(", ")} };`,
  "",
].join("\n");
writeFileSync(join(dist, "loam.mjs"), out);

const got = Object.keys(await import(pathToFileURL(join(dist, "loam.mjs")).href)).sort();
if (got.join() !== names.join()) {
  throw new Error(`bundle: loam.mjs exports ${got.join(", ")}, dist/index.js ${names.join(", ")}`);
}
console.log(`dist/loam.mjs: ${order.length - 1} modules, ${names.length} exports, ${out.length} bytes`);
